create policy "tickets_insert_owner"
on public.tickets for insert to authenticated
with check (
  exists (
    select 1 from public.authors
    where authors.id = tickets.author_id and authors.user_id = (select auth.uid())
  )
  and assigned_to is null
  and status = 'Open'
  and priority = 'Medium'
);

create policy "tickets_update_admin"
on public.tickets for update to authenticated
using (coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), '') in ('admin', 'ops'))
with check (coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), '') in ('admin', 'ops'));

create policy "messages_select_visible_ticket"
on public.ticket_messages for select to authenticated
using (
  exists (
    select 1
    from public.tickets
    join public.authors on authors.id = tickets.author_id
    where tickets.id = ticket_messages.ticket_id
      and (
        authors.user_id = (select auth.uid())
        or coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), '') in ('admin', 'ops')
      )
  )
);

create policy "messages_insert_author"
on public.ticket_messages for insert to authenticated
with check (
  sender = 'author'
  and sender_user_id = (select auth.uid())
  and exists (
    select 1
    from public.tickets
    join public.authors on authors.id = tickets.author_id
    where tickets.id = ticket_messages.ticket_id
      and authors.user_id = (select auth.uid())
      and tickets.status <> 'Closed'
  )
);

create policy "messages_insert_admin"
on public.ticket_messages for insert to authenticated
with check (
  sender = 'admin'
  and sender_user_id = (select auth.uid())
  and coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), '') in ('admin', 'ops')
);

