create policy "authors_select_own_or_admin"
on public.authors for select to authenticated
using (
  (select auth.uid()) = user_id
  or coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), '') in ('admin', 'ops')
);

create policy "staff_select_admin"
on public.staff_profiles for select to authenticated
using (coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), '') in ('admin', 'ops'));
create policy "staff_insert_admin"
on public.staff_profiles for insert to authenticated
with check (coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), '') = 'admin');
create policy "staff_update_admin"
on public.staff_profiles for update to authenticated
using (coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), '') = 'admin')
with check (coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), '') = 'admin');
create policy "staff_delete_admin"
on public.staff_profiles for delete to authenticated
using (coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), '') = 'admin');

create policy "books_select_owner_or_admin"
on public.books for select to authenticated
using (
  exists (
    select 1 from public.authors
    where authors.id = books.author_id and authors.user_id = (select auth.uid())
  )
  or coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), '') in ('admin', 'ops')
);

create policy "payouts_select_owner_or_admin"
on public.royalty_payouts for select to authenticated
using (
