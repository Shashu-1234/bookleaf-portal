create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create type public.ticket_category as enum (
  'Royalty & Payments',
  'ISBN & Metadata Issues',
  'Printing & Quality',
  'Distribution & Availability',
  'Book Status & Production Updates',
  'General Inquiry'
);

create type public.ticket_priority as enum ('Critical', 'High', 'Medium', 'Low');
create type public.ticket_status as enum ('Open', 'In Progress', 'Resolved', 'Closed');
create type public.message_sender as enum ('author', 'admin');
create type public.ai_run_state as enum ('ready', 'manual_review', 'failed');
create type public.payout_status as enum ('Paid', 'Processing', 'Failed');

create table public.authors (
  id text primary key check (id ~ '^AUTH[0-9]{3,}$'),
  user_id uuid unique references auth.users(id) on delete set null,
  name text not null check (char_length(name) between 2 and 120),
  email text not null check (email = lower(email) and email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
  phone text,
  city text,
  joined_date date not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index authors_email_unique on public.authors (lower(email));
create index authors_user_id_idx on public.authors (user_id) where user_id is not null;

create table public.staff_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null check (char_length(display_name) between 2 and 120),
  email text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.books (
  id text primary key check (id ~ '^BK[0-9]{3,}$'),
  author_id text not null references public.authors(id) on update cascade on delete restrict,
  title text not null check (char_length(title) between 1 and 240),
  isbn text not null unique,
  genre text not null,
  publication_date date,
  status text not null,
  mrp numeric(10, 2) check (mrp is null or mrp >= 0),
  author_royalty_per_copy numeric(10, 2) check (author_royalty_per_copy is null or author_royalty_per_copy >= 0),
  total_copies_sold integer not null default 0 check (total_copies_sold >= 0),
  total_royalty_earned numeric(12, 2) not null default 0 check (total_royalty_earned >= 0),
  royalty_paid numeric(12, 2) not null default 0 check (royalty_paid >= 0),
  royalty_pending numeric(12, 2) not null default 0 check (royalty_pending >= 0),
  last_royalty_payout_date date,
  print_partner text,
  available_on text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (royalty_paid + royalty_pending <= total_royalty_earned + 0.01)
);

create index books_author_id_idx on public.books (author_id);
create index books_status_idx on public.books (status);

create table public.royalty_payouts (
  id uuid primary key default gen_random_uuid(),
  author_id text not null references public.authors(id) on update cascade on delete restrict,
  book_id text references public.books(id) on update cascade on delete restrict,
  period_start date not null,
  period_end date not null,
  amount numeric(12, 2) not null check (amount > 0),
  status public.payout_status not null default 'Processing',
  paid_at timestamptz,
  reference text unique,
  created_at timestamptz not null default now(),
  check (period_end >= period_start),
  check ((status = 'Paid' and paid_at is not null) or status <> 'Paid')
);

create index royalty_payouts_author_date_idx on public.royalty_payouts (author_id, paid_at desc nulls last);
create index royalty_payouts_book_id_idx on public.royalty_payouts (book_id) where book_id is not null;

create table public.tickets (
  id uuid primary key default gen_random_uuid(),
  ticket_number bigint generated by default as identity (start with 1049) unique,
  author_id text not null references public.authors(id) on update cascade on delete restrict,
  book_id text references public.books(id) on update cascade on delete set null,
  subject text not null check (char_length(subject) between 8 and 160),
  description text not null check (char_length(description) between 20 and 4000),
  category public.ticket_category not null,
  priority public.ticket_priority not null default 'Medium',
  status public.ticket_status not null default 'Open',
  assigned_to uuid references public.staff_profiles(user_id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz,
  closed_at timestamptz,
  check (resolved_at is null or status in ('Resolved', 'Closed')),
  check (closed_at is null or status = 'Closed')
);

create index tickets_author_created_idx on public.tickets (author_id, created_at desc);
create index tickets_queue_idx on public.tickets (status, priority, created_at);
create index tickets_assignee_status_idx on public.tickets (assigned_to, status) where assigned_to is not null;
create index tickets_unresolved_age_idx on public.tickets (priority, created_at)
  where status in ('Open', 'In Progress');

create table public.ticket_messages (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.tickets(id) on delete cascade,
  sender public.message_sender not null,
  sender_user_id uuid not null references auth.users(id) on delete restrict,
  sender_name text not null check (char_length(sender_name) between 2 and 120),
  body text not null check (char_length(body) between 1 and 4000),
  created_at timestamptz not null default now()
);

create index ticket_messages_ticket_created_idx on public.ticket_messages (ticket_id, created_at);

create table public.internal_notes (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.tickets(id) on delete cascade,
  author_user_id uuid not null references public.staff_profiles(user_id) on delete restrict,
  body text not null check (char_length(body) between 1 and 4000),
  created_at timestamptz not null default now()
);

create index internal_notes_ticket_created_idx on public.internal_notes (ticket_id, created_at);

create table public.ai_runs (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.tickets(id) on delete cascade,
  state public.ai_run_state not null,
  suggested_category public.ticket_category,
  suggested_priority public.ticket_priority,
  confidence numeric(4, 3) check (confidence is null or confidence between 0 and 1),
  rationale text,
  urgency_signals text[] not null default '{}',
  draft_subject text,
  draft_body text,
  policy_references text[] not null default '{}',
  provider text,
  model text,
  input_tokens integer check (input_tokens is null or input_tokens >= 0),
  output_tokens integer check (output_tokens is null or output_tokens >= 0),
  latency_ms integer check (latency_ms is null or latency_ms >= 0),
  error_code text,
  created_at timestamptz not null default now()
);

create index ai_runs_ticket_created_idx on public.ai_runs (ticket_id, created_at desc);

create function private.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger authors_set_updated_at before update on public.authors
for each row execute function private.set_updated_at();
create trigger staff_profiles_set_updated_at before update on public.staff_profiles
for each row execute function private.set_updated_at();
create trigger books_set_updated_at before update on public.books
for each row execute function private.set_updated_at();
create trigger tickets_set_updated_at before update on public.tickets
for each row execute function private.set_updated_at();

